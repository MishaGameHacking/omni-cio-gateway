BEGIN;

-- A source correction receives a new revision, so a read-all acknowledgement
-- cannot mark a concurrent correction (or a newly arrived event) as read.
ALTER TABLE workspace_events ADD COLUMN IF NOT EXISTS revision bigint
    GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE workspace_events ADD COLUMN IF NOT EXISTS updated_at timestamptz
    NOT NULL DEFAULT now();
CREATE INDEX IF NOT EXISTS workspace_events_user_revision_idx
    ON workspace_events (user_id, revision);

CREATE TABLE IF NOT EXISTS notification_channels (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind text NOT NULL CHECK (kind IN ('push', 'email')),
    destination_hash text NOT NULL CHECK (destination_hash ~ '^[0-9a-f]{64}$'),
    destination_ciphertext bytea NOT NULL,
    label text NOT NULL CHECK (char_length(label) BETWEEN 1 AND 100),
    status text NOT NULL CHECK (status IN ('pending', 'active', 'revoked', 'expired')),
    verification_digest bytea,
    verification_expires_at timestamptz,
    verification_attempts integer NOT NULL DEFAULT 0
        CHECK (verification_attempts BETWEEN 0 AND 5),
    last_verification_at timestamptz,
    event_revision bigint NOT NULL DEFAULT 0 CHECK (event_revision >= 0),
    digest_period text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    verified_at timestamptz,
    UNIQUE (user_id, id),
    UNIQUE (user_id, kind, destination_hash)
);

CREATE TABLE IF NOT EXISTS notification_outbox (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    channel_id uuid NOT NULL,
    FOREIGN KEY (user_id, channel_id) REFERENCES notification_channels(user_id, id)
        ON DELETE CASCADE,
    message_key text NOT NULL CHECK (char_length(message_key) BETWEEN 1 AND 160),
    kind text NOT NULL CHECK (kind IN ('event', 'digest', 'verification', 'operational')),
    payload_ciphertext bytea NOT NULL,
    status text NOT NULL DEFAULT 'queued'
        CHECK (status IN ('queued', 'sending', 'accepted', 'failed', 'cancelled', 'uncertain')),
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 6),
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    lease_until timestamptz,
    lease_token uuid,
    last_error text CHECK (last_error IS NULL OR last_error ~ '^[a-z0-9_]{1,80}$'),
    created_at timestamptz NOT NULL DEFAULT now(),
    accepted_at timestamptz,
    UNIQUE (user_id, channel_id, message_key)
);
CREATE INDEX IF NOT EXISTS notification_outbox_due_idx
    ON notification_outbox (user_id, next_attempt_at)
    WHERE status IN ('queued', 'sending');

ALTER TABLE notification_channels ENABLE ROW LEVEL SECURITY;
ALTER TABLE notification_channels FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS notification_channels_tenant ON notification_channels;
CREATE POLICY notification_channels_tenant ON notification_channels
    USING (user_id = NULLIF(current_setting('omnicio.user_id', true), '')::uuid)
    WITH CHECK (user_id = NULLIF(current_setting('omnicio.user_id', true), '')::uuid);
ALTER TABLE notification_outbox ENABLE ROW LEVEL SECURITY;
ALTER TABLE notification_outbox FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS notification_outbox_tenant ON notification_outbox;
CREATE POLICY notification_outbox_tenant ON notification_outbox
    USING (user_id = NULLIF(current_setting('omnicio.user_id', true), '')::uuid)
    WITH CHECK (user_id = NULLIF(current_setting('omnicio.user_id', true), '')::uuid);

COMMIT;
