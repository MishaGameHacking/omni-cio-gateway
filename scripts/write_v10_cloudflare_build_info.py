from __future__ import annotations

import os
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "cloudflare/src/generated-build-info.js"
_SHA = re.compile(r"^[0-9a-f]{40}$")


def _source_sha() -> str:
    candidates = (
        os.environ.get("WORKERS_CI_COMMIT_SHA", ""),
        os.environ.get("GITHUB_SHA", ""),
    )
    for value in candidates:
        normalized = value.strip().lower()
        if normalized:
            if _SHA.fullmatch(normalized) is None:
                raise RuntimeError("CLOUDFLARE_BUILD_SOURCE_SHA_INVALID")
            return normalized
    raise RuntimeError("CLOUDFLARE_BUILD_SOURCE_SHA_REQUIRED")


def main() -> int:
    try:
        source_sha = _source_sha()
    except RuntimeError as exc:
        print(str(exc), file=sys.stderr)
        return 1
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(
        "// Generated by scripts/write_v10_cloudflare_build_info.py; do not edit.\n"
        f'export const SOURCE_SHA = "{source_sha}";\n',
        encoding="utf-8",
    )
    print(f"Cloudflare source identity generated for {source_sha}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
